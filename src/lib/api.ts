import { invoke } from "@tauri-apps/api/core";
import type * as T from "./types";

const c = <R>(cmd: string, args?: Record<string, unknown>) => invoke<R>(cmd, args);

export const api = {
  getSettings: () => c<T.Settings>("get_settings"),
  setSettings: (settings: T.Settings) => c<T.Settings>("set_settings", { settings }),
  getPaused: () => c<boolean>("get_paused"),
  setPaused: (paused: boolean) => c<void>("set_paused", { paused }),
  setView: (view: string) => c<void>("set_view", { view }),
  getSnapshot: () => c<T.SystemSnap | null>("get_snapshot"),
  getProcesses: () => c<T.ProcRow[]>("get_processes"),
  processIcon: (path: string) => c<string | null>("process_icon", { path }),
  terminate: (pid: number, createTime: string, name: string) => c<void>("terminate_process", { pid, createTime, name }),

  historySeries: (from: number, to: number, maxPoints = 600) => c<T.Point[]>("history_series", { from, to, maxPoints }),
  historySnapAt: (ts: number) => c<T.SnapAt | null>("history_snap_at", { ts }),
  historySpikes: (from: number, to: number, limit = 200) => c<T.SpikeRow[]>("history_spikes", { from, to, limit }),
  historyPeaks: (from: number, to: number, limit = 25) => c<T.PeakRow[]>("history_peaks", { from, to, limit }),
  historyApp: (name: string, from: number, to: number) => c<[number, number][]>("history_app", { name, from, to }),
  historyGrowth: (windowMin = 60) => c<T.GrowthRow[]>("history_growth", { windowMin }),
  historyAlerts: () => c<T.AlertRow[]>("history_alerts"),
  storeInfo: () => c<T.StoreInfo>("store_info"),
  clearHistory: () => c<void>("clear_history"),
  exportCsv: (from: number, to: number, path: string) => c<number>("export_csv", { from, to, path }),
  attention: () => c<T.Attention[]>("attention"),

  drives: () => c<T.Drive[]>("drives_list"),
  scanStart: (roots: string[]) => c<void>("scan_start", { roots }),
  scanCancel: () => c<void>("scan_cancel"),
  scanList: () => c<T.ScanMeta[]>("scan_list"),
  scanOpen: (id: string) => c<T.ScanMeta>("scan_open", { id }),
  scanDelete: (id: string) => c<void>("scan_delete", { id }),
  scanState: () => c<{ scanning: boolean; current: string | null; loaded: boolean }>("scan_state"),
  treeChildren: (node: number, metric: string, limit = 500) => c<T.Children>("tree_children", { node, metric, limit }),
  treeTreemap: (node: number, metric: string, depth = 3) => c<T.Tm>("tree_treemap", { node, metric, depth }),
  treeCrumbs: (node: number) => c<T.Crumb[]>("tree_crumbs", { node }),
  treeFind: (path: string) => c<number | null>("tree_find", { path }),
  treeSearch: (filter: T.Filter) => c<T.SearchResult>("tree_search", { filter }),
  storageOverview: () => c<T.Overview>("storage_overview"),
  storageLocations: () => c<T.Location[]>("storage_locations"),
  storageLocChildren: (path: string) => c<T.Row[]>("storage_loc_children", { path }),
  storageInstallers: () => c<T.Row[]>("storage_installers"),
  storageApps: () => c<T.App[]>("storage_apps"),
  storageDiff: (a: string, b: string) => c<T.Diff>("storage_diff", { a, b }),
  dupStart: (minSizeMb: number) => c<void>("dup_start", { minSizeMb }),
  dupCancel: () => c<void>("dup_cancel"),
  dupResult: () => c<T.DupGroup[] | null>("dup_result"),

  reveal: (path: string) => c<void>("act_reveal", { path }),
  openFolder: (path: string) => c<void>("act_open", { path }),
  props: (path: string) => c<void>("act_props", { path }),
  recycle: (paths: string[]) => c<number>("act_recycle", { paths }),
  system: (target: string) => c<void>("act_system", { target }),
  isProtected: (path: string) => c<string | null>("act_protected", { path }),

  hardware: () => c<T.Inventory>("hardware_info"),
  sensorHub: () => c<T.HubData>("sensor_hub"),
  autostartGet: () => c<boolean>("autostart_get"),
  autostartSet: (enabled: boolean) => c<void>("autostart_set", { enabled }),
  lhmInfo: () => c<{ installed: boolean; path: string }>("lhm_info"),
  lhmLaunch: () => c<void>("lhm_launch"),
  appInfo: () => c<T.AppInfo>("app_info"),
};
